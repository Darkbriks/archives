CREATE OR REPLACE PROCEDURE Produit_Vendu(p_numero_produit IN PRODUITS.NUMERO%TYPE, p_quantite_vendue IN NUMBER)
IS
    v_prix_unitaire PRODUITS.PRIXUNITAIRE%TYPE;
    v_numero_rayon PRODUITS.NUMERORAYON%TYPE;
    v_quantite_stock PRODUITS.QUANTITESTOCKHYPER%TYPE;
    v_chiffre_affaire RAYON.CHIFFREAFFAIRE%TYPE;
BEGIN
    SELECT PRIXUNITAIRE, NUMERORAYON, QUANTITESTOCKHYPER INTO v_prix_unitaire, v_numero_rayon, v_quantite_stock FROM PRODUITS
    WHERE NUMERO = p_numero_produit;

    IF v_quantite_stock < p_quantite_vendue THEN
        RAISE_APPLICATION_ERROR(-20001, 'Pas assez de stock pour le produit.');
    END IF;

    UPDATE PRODUITS SET QUANTITESTOCKHYPER = QUANTITESTOCKHYPER - p_quantite_vendue WHERE NUMERO = p_numero_produit;

    DECLARE
        v_montant_vente NUMBER;
    BEGIN
        v_montant_vente := v_prix_unitaire * p_quantite_vendue;

        UPDATE RAYON SET CHIFFREAFFAIRE = CHIFFREAFFAIRE + v_montant_vente WHERE NUMERO = v_numero_rayon;
    END;

    DBMS_OUTPUT.PUT_LINE('Produit vendu avec succès.');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20002, 'Produit introuvable.');
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20003, 'Erreur inattendue : ' || SQLERRM);
END Produit_Vendu;
/

BEGIN
    Produit_Vendu('PR1234', 10);
END;
