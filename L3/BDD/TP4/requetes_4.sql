DROP TABLE Primes;
CREATE TABLE Primes (
    numero NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numeroEmploye VARCHAR2(7) NOT NULL,
    numeroRayon VARCHAR2(7) NOT NULL,
    montantPrime NUMBER(10, 2) NOT NULL,
    moisAnnee VARCHAR2(7) NOT NULL
);

-- 4.1
CREATE OR REPLACE PROCEDURE Attribuer_Primes_IF(p_prime1 NUMBER, p_prime2 NUMBER, p_prime3 NUMBER, p_moisAnnee VARCHAR2)
IS
    CURSOR c_top_rayons IS
        SELECT r.NUMERO AS numero_rayon, r.NUMERORESPONSABLE AS numero_employe, r.CHIFFREAFFAIRE AS chiffre_affaire,
               RANK() OVER (PARTITION BY r.NUMEROHYPER ORDER BY r.CHIFFREAFFAIRE DESC) AS rang
        FROM RAYON r
        INNER JOIN HYPERMARCHE h ON r.NUMEROHYPER = h.NUMERO  WHERE h.CODEPOSTAL like '59%' OR h.CODEPOSTAL like '62%';

    v_numero_rayon RAYON.NUMERO%TYPE;
    v_numero_employe RAYON.NUMERORESPONSABLE%TYPE;
    v_chiffre_affaire RAYON.CHIFFREAFFAIRE%TYPE;
    v_rang NUMBER := 0;

BEGIN
    OPEN c_top_rayons;

    LOOP
        FETCH c_top_rayons INTO v_numero_rayon, v_numero_employe, v_chiffre_affaire, v_rang;
        EXIT WHEN c_top_rayons%NOTFOUND;

        IF v_rang = 1 THEN
            INSERT INTO Primes (numeroEmploye, numeroRayon, montantPrime, moisAnnee) VALUES (v_numero_employe, v_numero_rayon, p_prime1, p_moisAnnee);
        ELSIF v_rang = 2 THEN
            INSERT INTO Primes (numeroEmploye, numeroRayon, montantPrime, moisAnnee) VALUES (v_numero_employe, v_numero_rayon, p_prime2, p_moisAnnee);
        ELSIF v_rang = 3 THEN
            INSERT INTO Primes (numeroEmploye, numeroRayon, montantPrime, moisAnnee) VALUES (v_numero_employe, v_numero_rayon, p_prime3, p_moisAnnee);
        END IF;
    END LOOP;

    CLOSE c_top_rayons;
END Attribuer_Primes_IF;
/

BEGIN
    Attribuer_Primes_IF(1000, 500, 250, '2025-01');
END;
