IS
    CURSOR c_top_rayons IS
        SELECT r.NUMERO AS numero_rayon, r.NUMERORESPONSABLE AS numero_employe, r.CHIFFREAFFAIRE AS chiffre_affaire,
               RANK() OVER (PARTITION BY r.NUMEROHYPER ORDER BY r.CHIFFREAFFAIRE DESC) AS rang
        FROM RAYON r
        INNER JOIN HYPERMARCHE h ON r.NUMEROHYPER = h.NUMERO  WHERE h.CODEPOSTAL like '59%' OR h.CODEPOSTAL like '62%';

    v_numero_rayon RAYON.NUMERO%TYPE;
    v_numero_employe RAYON.NUMERORESPONSABLE%TYPE;
    v_chiffre_affaire RAYON.CHIFFREAFFAIRE%TYPE;
    v_rang NUMBER;

BEGIN
    OPEN c_top_rayons;

    LOOP
        FETCH c_top_rayons INTO v_numero_rayon, v_numero_employe, v_chiffre_affaire, v_rang;
        EXIT WHEN c_top_rayons%NOTFOUND;

        IF v_rang <= 3 THEN
            INSERT INTO Primes (numeroEmploye, numeroRayon, montantPrime, moisAnnee)
            VALUES (v_numero_employe, v_numero_rayon,
                CASE
                    WHEN v_rang = 1 THEN p_prime1
