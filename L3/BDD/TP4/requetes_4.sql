CREATE OR REPLACE PROCEDURE Afficher_Cumul_Primes(p_numero_magasin IN HYPERMARCHE.NUMERO%TYPE) IS
BEGIN
    FOR rec IN (
        SELECT r.NUMERORESPONSABLE AS numero_responsable, Get_Emp_Name(r.NUMERORESPONSABLE) AS nom_responsable, COALESCE(SUM(p.montantPrime), 0) AS cumul_primes FROM RAYON r
        LEFT JOIN Primes p ON r.NUMERO = p.numeroRayon WHERE r.NUMEROHYPER = p_numero_magasin
        GROUP BY r.NUMERORESPONSABLE ORDER BY cumul_primes DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE('Responsable: ' || rec.nom_responsable || ' (Numéro: ' || rec.numero_responsable || ')' || ', Cumul des primes: ' || rec.cumul_primes);
    END LOOP;
END Afficher_Cumul_Primes;
/

BEGIN
    Attribuer_Primes_CASE(100, 50, 25, '2025-02');
    Afficher_Cumul_Primes('HYP56');
END;
