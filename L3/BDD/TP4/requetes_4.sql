CREATE OR REPLACE PROCEDURE Afficher_Top3_Rayons(p_numero_hyper IN HYPERMARCHE.NUMERO%TYPE)
IS
    CURSOR c_top_rayons IS
        SELECT r.NOM AS nom_rayon, r.CHIFFREAFFAIRE AS chiffre_affaire, r.NUMERORESPONSABLE AS numero_responsable FROM RAYON r
        WHERE r.NUMEROHYPER = p_numero_hyper
        ORDER BY r.CHIFFREAFFAIRE DESC
        FETCH FIRST 3 ROWS ONLY;

    v_nom_rayon RAYON.NOM%TYPE;
    v_chiffre_affaire RAYON.CHIFFREAFFAIRE%TYPE;
    v_numero_responsable RAYON.NUMERORESPONSABLE%TYPE;
    v_nom_responsable VARCHAR2(101);
BEGIN
    OPEN c_top_rayons;

    LOOP
        FETCH c_top_rayons INTO v_nom_rayon, v_chiffre_affaire, v_numero_responsable;
        EXIT WHEN c_top_rayons%NOTFOUND;

        v_nom_responsable := Get_Emp_Name(v_numero_responsable);
        DBMS_OUTPUT.PUT_LINE('Rayon: ' || v_nom_rayon || ', Chiffre d''affaires: ' || v_chiffre_affaire || ', Responsable: ' || NVL(v_nom_responsable, 'Non attribué'));
    END LOOP;

    CLOSE c_top_rayons;
END Afficher_Top3_Rayons;
/

BEGIN
    Afficher_Top3_Rayons('HYP56');
END;
/
