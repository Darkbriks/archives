CREATE OR REPLACE FUNCTION Get_Emp_Name(p_numero_employe IN EMPLOYE.NUMERO%TYPE)
    RETURN VARCHAR2 IS v_full_name VARCHAR2(101);
BEGIN
    SELECT NOM || ' ' || PRENOM INTO v_full_name FROM EMPLOYE WHERE NUMERO = p_numero_employe;
    RETURN v_full_name;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END Get_Emp_Name;
/
